    // 74. (Doc #76) BRIMSTONE FOOTPRINT -- landing reaction zone
    // =========================================================================
    public static class BrimstoneFootprint extends EnvironmentalAttack {

        private final List<BlockDisplayHandle> craterHandles = new ArrayList<>();
        private Location landingPoint;
        private boolean erupted = false;
        private int eruptTick = -1;

        public BrimstoneFootprint(ChaosCraftPlugin plugin) {
            super(plugin, new AttackConfig("brimstone_footprint", AttackType.ENVIRONMENTAL, 4));
            config.setDamage(0.0);
            config.setDamageRadius(0.0);
            config.setDurationTicks(200); // 10 seconds
            config.setCooldownTicks(300); // Triggers on Dragon landing
            config.setTicksBetweenDamage(999);
        }

        @Override
        protected void onSpawn(Location center) {
            World w = center.getWorld();
            if (w == null) return;

            landingPoint = center.clone();

            // Swirling lava + flame at landing point
            w.spawnParticle(Particle.LAVA, landingPoint, 20, 1, 1, 1, 0);
            w.spawnParticle(Particle.FLAME, landingPoint.clone().add(0, 0.5, 0), 30, 2, 1, 2, 0.03);
        }

        @Override
        protected void onTick(int ticksAlive) {
            Location center = getCenter();
            if (center == null || landingPoint == null) return;
            World w = center.getWorld();
            if (w == null) return;

            // Buildup: 40 ticks (2 seconds)
            if (ticksAlive <= 40) {
                if (ticksAlive % 5 == 0) {
                    w.spawnParticle(Particle.LAVA, landingPoint, 10, 1.5, 0.5, 1.5, 0);
                    w.spawnParticle(Particle.FLAME, landingPoint.clone().add(0, 0.5, 0), 15, 2, 0.5, 2, 0.02);
                }
                return;
            }

            // Eruption
            if (!erupted) {
                erupted = true;
                eruptTick = ticksAlive;

                DisplayBuilder.playSound(landingPoint, Sound.BLOCK_NETHERRACK_BREAK, 1.0f, 0.4f);
                DisplayBuilder.playSound(landingPoint, Sound.ENTITY_BLAZE_SHOOT, 0.6f, 0.5f);

                // Center burst
                w.spawnParticle(Particle.LAVA, landingPoint, 40, 2, 1, 2, 0);
                w.spawnParticle(Particle.FLAME, landingPoint, 60, 3, 2, 3, 0.05);

                // Entry damage: 8 in 8-block radius
                for (Player p : w.getPlayers()) {
                    if (isExempt(p)) continue;
                    if (p.getLocation().distanceSquared(landingPoint) <= 64.0) {
                        p.damage(16.0); // 8 hearts
                    }
                }

                // Crater displays
                for (int i = 0; i < 6; i++) {
                    double a = (2 * Math.PI * i) / 6;
                    Location cratLoc = landingPoint.clone().add(Math.cos(a) * 3, 0.05, Math.sin(a) * 3);
                    BlockDisplayHandle h = displayBuilder.spawnBlock(cratLoc, Material.MAGMA_BLOCK);
                    h.scale(1.5f, 0.15f, 1.5f).glow(200, 0, 50).interpolation(5, 0);
                    craterHandles.add(h);
                    spawnedEntities.add(h.entity());
                }

                // Three radial fire cracks
                for (int c = 0; c < 3; c++) {
                    double crackAngle = Math.random() * 2 * Math.PI;
                    for (int step = 0; step < 10; step++) {
                        Location crackPos = landingPoint.clone().add(
                                Math.cos(crackAngle) * (step + 1), 0.2,
                                Math.sin(crackAngle) * (step + 1));
                        w.spawnParticle(Particle.FLAME, crackPos, 3, 0.1, 0.3, 0.1, 0.01);
                    }
                }
            }

            // Ground fire: 3/sec for 6 seconds (120 ticks)
            if (eruptTick > 0 && ticksAlive - eruptTick <= 120) {
                if ((ticksAlive - eruptTick) % 4 == 0) {
                    w.spawnParticle(Particle.FLAME, landingPoint.clone().add(0, 0.3, 0), 10, 4, 0.3, 4, 0.01);
                }
                if ((ticksAlive - eruptTick) % 20 == 0) {
                    for (Player p : w.getPlayers()) {
                        if (isExempt(p)) continue;
                        if (p.getLocation().distanceSquared(landingPoint) <= 64.0) {
                            p.damage(6.0); // 3 hearts fire per second
                        }
                    }
                }
            }
        }

        @Override
        protected void onCleanup() { displayBuilder.removeAll(); }

        @Override
        public AbstractAttack newInstance() { return new BrimstoneFootprint(plugin); }
    }

