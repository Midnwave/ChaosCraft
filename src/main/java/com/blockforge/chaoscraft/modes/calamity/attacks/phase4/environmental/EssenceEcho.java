    // 71. PILLAR COLLAPSE WAVE -- crystal pillars collapse in rotating sequence
    // (Design doc #71 -- Pillar Collapse Wave)
    // =========================================================================
    public static class FlameEchoTrail extends EnvironmentalAttack {

        private final List<Location> trailZones = new ArrayList<>();
        private Location trailStart;
        private double trailAngle;

        public FlameEchoTrail(ChaosCraftPlugin plugin) {
            super(plugin, new AttackConfig("flame_echo_trail", AttackType.ENVIRONMENTAL, 4));
            config.setDamage(0.0);
            config.setDamageRadius(0.0);
            config.setDurationTicks(220); // 11 seconds
            config.setCooldownTicks(300); // Triggers after firebreath
            config.setTicksBetweenDamage(999);
        }

        @Override
        protected void onSpawn(Location center) {
            World w = center.getWorld();
            if (w == null) return;

            trailStart = center.clone();
            trailAngle = Math.random() * 2 * Math.PI;

            DisplayBuilder.playSound(center, Sound.ENTITY_BLAZE_SHOOT, 0.2f, 0.8f);
        }

        @Override
        protected void onTick(int ticksAlive) {
            Location center = getCenter();
            if (center == null || trailStart == null) return;
            World w = center.getWorld();
            if (w == null) return;

            // Trail formation: first 60 ticks (3 seconds) -- placing zones along path
            if (ticksAlive <= 60 && ticksAlive % 3 == 0) {
                // Dragon's simulated flight path
                double pathProgress = ticksAlive / 60.0;
                double pathDist = pathProgress * 25;
                Location zonePos = trailStart.clone().add(
                        Math.cos(trailAngle) * pathDist,
                        3 + Math.sin(pathProgress * Math.PI) * 5, // Arc upward
                        Math.sin(trailAngle) * pathDist
                );
                trailZones.add(zonePos);

                // FLAME particles at zone
                w.spawnParticle(Particle.FLAME, zonePos, 5, 0.3, 0.3, 0.3, 0.02);
                DisplayBuilder.playSound(zonePos, Sound.ENTITY_BLAZE_SHOOT, 0.15f, 0.8f);
            }

            // Active zones: FLAME particles + damage for 8 seconds (160 ticks)
            if (ticksAlive > 10) {
                // Particle maintenance
                if (ticksAlive % 6 == 0) {
                    for (Location zone : trailZones) {
                        w.spawnParticle(Particle.FLAME, zone, 3, 0.5, 0.5, 0.5, 0.01);
                    }
                }

                // Damage: 3 fire per second per zone
                if (ticksAlive % 20 == 0) {
                    for (Location zone : trailZones) {
                        for (Player p : w.getPlayers()) {
                            if (isExempt(p)) continue;
                            if (p.getLocation().distanceSquared(zone) <= 2.25) { // 1.5 radius
                                p.damage(6.0); // 3 hearts
                                break; // Only damage once per tick
                            }
                        }
                    }
                }
            }
        }

        @Override
        protected void onCleanup() { displayBuilder.removeAll(); }

        @Override
        public AbstractAttack newInstance() { return new FlameEchoTrail(plugin); }
    }

