    // 73. (Doc #75) CRYSTAL ECHO: AMETHYST SCATTER -- pillar fires shards radially
    // =========================================================================
    public static class CrystalEchoScatter extends EnvironmentalAttack {

        private Location pillarPos;
        private boolean shattered = false;

        public CrystalEchoScatter(ChaosCraftPlugin plugin) {
            super(plugin, new AttackConfig("crystal_echo_scatter", AttackType.ENVIRONMENTAL, 4));
            config.setDamage(0.0);
            config.setDamageRadius(0.0);
            config.setDurationTicks(120); // 6 seconds
            config.setCooldownTicks(400); // Triggers on Dragon proximity
            config.setTicksBetweenDamage(999);
        }

        @Override
        protected void onSpawn(Location center) {
            World w = center.getWorld();
            if (w == null) return;

            // Pillar near the spawn center
            double angle = Math.random() * 2 * Math.PI;
            pillarPos = center.clone().add(Math.cos(angle) * 12, 0, Math.sin(angle) * 12);

            // Warning: amethyst resonance
            DisplayBuilder.playSound(pillarPos, Sound.BLOCK_AMETHYST_CLUSTER_BREAK, 0.6f, 1.0f);
            w.spawnParticle(Particle.BLOCK, pillarPos.clone().add(0, 3, 0), 20, 0.5, 2, 0.5, 0,
                    Material.AMETHYST_BLOCK.createBlockData());
        }

        @Override
        protected void onTick(int ticksAlive) {
            Location center = getCenter();
            if (center == null || pillarPos == null) return;
            World w = center.getWorld();
            if (w == null) return;

            // Vibration warning: 20 ticks (1 second)
            if (ticksAlive <= 20) {
                if (ticksAlive % 5 == 0) {
                    w.spawnParticle(Particle.BLOCK, pillarPos.clone().add(0, 2, 0), 10, 0.5, 1.5, 0.5, 0,
                            Material.AMETHYST_BLOCK.createBlockData());
                }
                return;
            }

            // Fire shards in 8 directions
            if (!shattered) {
                shattered = true;

                DisplayBuilder.playSound(pillarPos, Sound.BLOCK_AMETHYST_CLUSTER_BREAK, 0.8f, 1.2f);
                w.spawnParticle(Particle.BLOCK, pillarPos, 60, 1, 2, 1, 0,
                        Material.AMETHYST_BLOCK.createBlockData());

                for (int dir = 0; dir < 8; dir++) {
                    double shardAngle = (2 * Math.PI * dir) / 8;
                    final double sa = shardAngle;

                    // Animate shard travel
                    for (int step = 0; step < 10; step++) {
                        final int s = step;
                        plugin.getServer().getScheduler().runTaskLater(plugin, () -> {
                            double dist = s + 1;
                            Location shardPos = pillarPos.clone().add(
                                    Math.cos(sa) * dist, 1.0, Math.sin(sa) * dist);
                            w.spawnParticle(Particle.BLOCK, shardPos, 6, 0.2, 0.2, 0.2, 0,
                                    Material.AMETHYST_BLOCK.createBlockData());
                            DisplayBuilder.playSound(shardPos, Sound.BLOCK_GLASS_BREAK, 0.3f, 0.8f);

                            // Damage at shard position
                            for (Player p : w.getPlayers()) {
                                if (isExempt(p)) continue;
                                if (p.getLocation().distanceSquared(shardPos) <= 4.0) { // 2 radius
                                    p.damage(10.0); // 5 hearts
                                }
                            }
                        }, step * 2L);
                    }
                }
            }

            // Aftermath: cracked pillar particles
            if (ticksAlive > 30 && ticksAlive <= 100 && ticksAlive % 10 == 0) {
                w.spawnParticle(Particle.BLOCK, pillarPos.clone().add(0, 1, 0), 5, 0.5, 1, 0.5, 0,
                        Material.AMETHYST_BLOCK.createBlockData());
            }
        }

        @Override
        protected void onCleanup() { displayBuilder.removeAll(); }

        @Override
        public AbstractAttack newInstance() { return new CrystalEchoScatter(plugin); }
    }

