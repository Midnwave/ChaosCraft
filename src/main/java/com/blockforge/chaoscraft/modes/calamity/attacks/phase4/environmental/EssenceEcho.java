    // 76. (Doc #78) DIVE PATH SCAR -- low altitude purple line across arena
    // =========================================================================
    public static class DivePathScar extends EnvironmentalAttack {

        private Location scarStart;
        private Location scarEnd;

        public DivePathScar(ChaosCraftPlugin plugin) {
            super(plugin, new AttackConfig("dive_path_scar", AttackType.ENVIRONMENTAL, 4));
            config.setDamage(0.0);
            config.setDamageRadius(0.0);
            config.setDurationTicks(200); // 10 seconds
            config.setCooldownTicks(300); // After each dive
            config.setTicksBetweenDamage(999);
        }

        @Override
        protected void onSpawn(Location center) {
            World w = center.getWorld();
            if (w == null) return;

            double angle = Math.random() * 2 * Math.PI;
            scarStart = center.clone().add(Math.cos(angle) * -18, 0, Math.sin(angle) * -18);
            scarEnd = center.clone().add(Math.cos(angle) * 18, 0, Math.sin(angle) * 18);
        }

        @Override
        protected void onTick(int ticksAlive) {
            Location center = getCenter();
            if (center == null || scarStart == null || scarEnd == null) return;
            World w = center.getWorld();
            if (w == null) return;

            // Persistent scar particles at Y+3 to Y+8
            if (ticksAlive % 5 == 0) {
                int linePoints = 20;
                for (int i = 0; i < linePoints; i++) {
                    double t = (double) i / linePoints;
                    double x = scarStart.getX() + (scarEnd.getX() - scarStart.getX()) * t;
                    double z = scarStart.getZ() + (scarEnd.getZ() - scarStart.getZ()) * t;
                    double y = center.getY() + 3 + Math.random() * 5;
                    w.spawnParticle(Particle.DRAGON_BREATH, new Location(w, x, y, z), 4, 0.5, 1, 0.5, 0.01);
                }
            }

            // Damage: 3/sec for players crossing the scar
            if (ticksAlive % 20 == 0) {
                for (Player p : w.getPlayers()) {
                    if (isExempt(p)) continue;
                    Location pl = p.getLocation();
                    // Distance to the scar line
                    double dist = distanceToLine(pl, scarStart, scarEnd);
                    if (dist <= 1.5 && pl.getY() >= center.getY() + 2 && pl.getY() <= center.getY() + 9) {
                        p.damage(6.0); // 3 hearts
                    }
                }
            }
        }

        private double distanceToLine(Location point, Location a, Location b) {
            double dx = b.getX() - a.getX();
            double dz = b.getZ() - a.getZ();
            double lenSq = dx * dx + dz * dz;
            if (lenSq == 0) return point.distance(a);
            double t = Math.max(0, Math.min(1, ((point.getX() - a.getX()) * dx + (point.getZ() - a.getZ()) * dz) / lenSq));
            double projX = a.getX() + t * dx;
            double projZ = a.getZ() + t * dz;
            return Math.sqrt(Math.pow(point.getX() - projX, 2) + Math.pow(point.getZ() - projZ, 2));
        }

        @Override
        protected void onCleanup() { displayBuilder.removeAll(); }

        @Override
        public AbstractAttack newInstance() { return new DivePathScar(plugin); }
    }

