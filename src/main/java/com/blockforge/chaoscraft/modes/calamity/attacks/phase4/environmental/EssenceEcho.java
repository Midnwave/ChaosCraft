    // 72. PRE-DEATH ENVIRONMENTAL CHAOS -- random attacks every 3 seconds at 3% HP
    // (Design doc #72 -- Pre-Death Environmental Chaos)
    // =========================================================================
    public static class VoidEchoTrail extends EnvironmentalAttack {

        private final List<Location> trailZones = new ArrayList<>();
        private Location chargeStart;
        private Location chargeEnd;

        public VoidEchoTrail(ChaosCraftPlugin plugin) {
            super(plugin, new AttackConfig("void_echo_trail", AttackType.ENVIRONMENTAL, 4));
            config.setDamage(0.0);
            config.setDamageRadius(0.0);
            config.setDurationTicks(180); // 9 seconds
            config.setCooldownTicks(300); // Triggers after void charge
            config.setTicksBetweenDamage(999);
        }

        @Override
        protected void onSpawn(Location center) {
            World w = center.getWorld();
            if (w == null) return;

            // Straight charge path across arena
            double angle = Math.random() * 2 * Math.PI;
            chargeStart = center.clone().add(Math.cos(angle) * -15, 0, Math.sin(angle) * -15);
            chargeEnd = center.clone().add(Math.cos(angle) * 15, 0, Math.sin(angle) * 15);
        }

        @Override
        protected void onTick(int ticksAlive) {
            Location center = getCenter();
            if (center == null || chargeStart == null || chargeEnd == null) return;
            World w = center.getWorld();
            if (w == null) return;

            // Trail placement: every 2 ticks for first 40 ticks
            if (ticksAlive <= 40 && ticksAlive % 2 == 0) {
                double t = ticksAlive / 40.0;
                Location zoneLoc = chargeStart.clone().add(
                        (chargeEnd.getX() - chargeStart.getX()) * t,
                        0.5,
                        (chargeEnd.getZ() - chargeStart.getZ()) * t
                );
                trailZones.add(zoneLoc);
                w.spawnParticle(Particle.DRAGON_BREATH, zoneLoc, 8, 0.5, 0.3, 0.5, 0.02);
            }

            // Active void zones: 5 dmg/sec for 6 seconds
            if (ticksAlive > 10 && ticksAlive <= 130) {
                // Particles
                if (ticksAlive % 6 == 0) {
                    for (Location zone : trailZones) {
                        w.spawnParticle(Particle.DRAGON_BREATH, zone, 4, 0.8, 0.3, 0.8, 0.01);
                    }
                }

                // Damage: 5 per second
                if (ticksAlive % 20 == 0) {
                    for (Location zone : trailZones) {
                        for (Player p : w.getPlayers()) {
                            if (isExempt(p)) continue;
                            if (p.getLocation().distanceSquared(zone) <= 4.0) { // 2 radius
                                p.damage(10.0); // 5 hearts
                                break;
                            }
                        }
                    }
                }
            }
        }

        @Override
        protected void onCleanup() { displayBuilder.removeAll(); }

        @Override
        public AbstractAttack newInstance() { return new VoidEchoTrail(plugin); }
    }

