    // 75. (Doc #77) ORBIT TRAIL DENSITY -- persistent ring at Dragon orbit altitude
    // =========================================================================
    public static class OrbitTrailDensity extends EnvironmentalAttack {

        private double orbitRadius;

        public OrbitTrailDensity(ChaosCraftPlugin plugin) {
            super(plugin, new AttackConfig("orbit_trail_density", AttackType.ENVIRONMENTAL, 4));
            config.setDamage(0.0);
            config.setDamageRadius(0.0);
            config.setDurationTicks(400); // 20 seconds
            config.setCooldownTicks(600); // After 3 orbits
            config.setTicksBetweenDamage(999);
        }

        @Override
        protected void onSpawn(Location center) {
            World w = center.getWorld();
            if (w == null) return;

            orbitRadius = 14 + Math.random() * 6; // 14-20 blocks
            DisplayBuilder.playSound(center, Sound.ENTITY_ENDER_DRAGON_AMBIENT, 0.2f, 0.5f);
        }

        @Override
        protected void onTick(int ticksAlive) {
            Location center = getCenter();
            if (center == null) return;
            World w = center.getWorld();
            if (w == null) return;

            double ringY = center.getY() + 12; // Y+12 above arena

            // Persistent ring particles
            if (ticksAlive % 4 == 0) {
                int points = 24;
                for (int i = 0; i < points; i++) {
                    double a = (2 * Math.PI * i) / points;
                    Location ringLoc = new Location(w,
                            center.getX() + Math.cos(a) * orbitRadius,
                            ringY,
                            center.getZ() + Math.sin(a) * orbitRadius);
                    w.spawnParticle(Particle.DRAGON_BREATH, ringLoc, 3, 0.3, 0.3, 0.3, 0.01);
                }
            }

            // Ambient sound
            if (ticksAlive % 40 == 0) {
                DisplayBuilder.playSound(center, Sound.ENTITY_ENDER_DRAGON_AMBIENT, 0.15f, 0.5f);
            }

            // Damage: 4/sec for players on the ring path at that altitude
            if (ticksAlive % 20 == 0) {
                for (Player p : w.getPlayers()) {
                    if (isExempt(p)) continue;
                    Location pl = p.getLocation();
                    double hDist = Math.sqrt(Math.pow(pl.getX() - center.getX(), 2) + Math.pow(pl.getZ() - center.getZ(), 2));
                    if (Math.abs(hDist - orbitRadius) <= 2.0 && Math.abs(pl.getY() - ringY) <= 3.0) {
                        p.damage(8.0); // 4 hearts
                    }
                }
            }
        }

        @Override
        protected void onCleanup() { displayBuilder.removeAll(); }

        @Override
        public AbstractAttack newInstance() { return new OrbitTrailDensity(plugin); }
    }

